/**
 * MiniCompiler — IR Generator
 * Phase 5: Generates Three-Address Code (TAC) and AST-based IR
 * Also builds a Control Flow Graph (CFG) structure
 *
 * TAC format:
 *   t1 = a + b          (binary operation)
 *   t2 = -t1            (unary operation)
 *   x = t2              (copy/assignment)
 *   ifFalse t2 goto L1  (conditional jump)
 *   goto L2             (unconditional jump)
 *   L1:                 (label)
 *   param t1            (function parameter)
 *   call f, 2           (function call)
 *   t3 = return_val     (call result)
 *   return t3           (return)
 */

'use strict';

// ═══════════════════════════════════════════════════════════
//  TAC Instruction types
// ═══════════════════════════════════════════════════════════
class IRGen {
  constructor(ast) {
    this.ast       = ast;
    this.tac       = [];    // Three-Address Code instructions
    this.tempCount = 0;
    this.labelCount = 0;
    this.currentFunc = null;
    this.cfg        = { blocks: [], edges: [] };
    this.currentBlock = null;
  }

  // ── Helpers ───────────────────────────────────────────
  newTemp()  { return `t${++this.tempCount}`; }
  newLabel() { return `L${++this.labelCount}`; }

  emit(instr) {
    this.tac.push(instr);
    if (this.currentBlock) this.currentBlock.instrs.push(instr);
  }

  newBlock(label) {
    const block = { label, instrs: [], succs: [] };
    this.cfg.blocks.push(block);
    this.currentBlock = block;
    return block;
  }

  addEdge(from, to, label = '') {
    if (from && to) {
      from.succs.push({ target: to.label, label });
      this.cfg.edges.push({ from: from.label, to: to.label, label });
    }
  }

  // ── Entry Point ───────────────────────────────────────
  generate() {
    const entryBlock = this.newBlock('ENTRY');
    this.visitProgram(this.ast);
    return {
      tac: this.tac,
      astIR: this.astIR(this.ast, 0),
      cfg: this.cfg,
    };
  }

  // ── Program ───────────────────────────────────────────
  visitProgram(prog) {
    if (!prog) return;
    this.emit({ kind: 'comment', text: '=== MiniLang IR — Three-Address Code ===' });
    this.emit({ kind: 'comment', text: 'Generated by MiniCompiler Phase 5: IR Generation' });
    this.emit({ kind: 'blank' });
    for (const stmt of (prog.body || [])) this.visitStmt(stmt);
  }

  // ── Statements ────────────────────────────────────────
  visitStmt(stmt) {
    if (!stmt) return;
    switch (stmt.nodeType) {
      case 'VarDecl':  this.visitVarDecl(stmt); break;
      case 'Function': this.visitFuncDecl(stmt); break;
      case 'If':       this.visitIf(stmt); break;
      case 'While':    this.visitWhile(stmt); break;
      case 'Return':   this.visitReturn(stmt); break;
      case 'Print':    this.visitPrint(stmt); break;
      case 'Block':    this.visitBlock(stmt); break;
      case 'ExprStmt': this.visitExprStmt(stmt); break;
      case 'Assign':   this.visitAssignStmt(stmt); break;
      default: break;
    }
  }

  visitVarDecl(stmt) {
    this.emit({ kind: 'comment', text: `VarDecl: ${stmt.varType} ${stmt.name}` });
    if (stmt.init) {
      const t = this.visitExpr(stmt.init);
      this.emit({ kind: 'copy', dest: stmt.name, src: t });
    } else {
      this.emit({ kind: 'copy', dest: stmt.name, src: this.defaultVal(stmt.varType) });
    }
  }

  defaultVal(type) {
    if (type === 'int' || type === 'float') return '0';
    if (type === 'bool') return 'false';
    if (type === 'string') return '""';
    return '0';
  }

  visitFuncDecl(stmt) {
    this.emit({ kind: 'blank' });
    this.emit({ kind: 'func_begin', name: stmt.name, returnType: stmt.returnType, params: stmt.params });

    const funcBlock = this.newBlock(`func_${stmt.name}`);

    this.currentFunc = stmt.name;
    // Emit parameter setup
    for (const param of (stmt.params || [])) {
      this.emit({ kind: 'param_decl', name: param.name, ptype: param.ptype });
    }
    this.emit({ kind: 'blank' });
    this.visitBlock(stmt.body);
    this.emit({ kind: 'func_end', name: stmt.name });
    this.currentFunc = null;
  }

  visitBlock(block) {
    if (!block) return;
    for (const stmt of (block.body || [])) this.visitStmt(stmt);
  }

  visitIf(stmt) {
    const labelFalse = this.newLabel();
    const labelEnd   = this.newLabel();

    this.emit({ kind: 'comment', text: `If statement` });
    const cond = this.visitExpr(stmt.condition);
    this.emit({ kind: 'if_false', cond, target: labelFalse });

    const trueBlock = this.newBlock(labelFalse + '_true');
    this.visitBlock(stmt.consequent);
    const afterTrueBlock = this.currentBlock;

    if (stmt.alternate) {
      this.emit({ kind: 'goto', target: labelEnd });
      this.emit({ kind: 'label', name: labelFalse });
      const falseBlock = this.newBlock(labelFalse);
      if (stmt.alternate.nodeType === 'If') this.visitIf(stmt.alternate);
      else this.visitBlock(stmt.alternate);
      this.emit({ kind: 'label', name: labelEnd });
      this.newBlock(labelEnd);
    } else {
      this.emit({ kind: 'label', name: labelFalse });
      this.newBlock(labelFalse);
    }
  }

  visitWhile(stmt) {
    const labelStart = this.newLabel();
    const labelEnd   = this.newLabel();

    this.emit({ kind: 'blank' });
    this.emit({ kind: 'comment', text: `While loop` });
    this.emit({ kind: 'label', name: labelStart });
    const loopBlock = this.newBlock(labelStart);

    const cond = this.visitExpr(stmt.condition);
    this.emit({ kind: 'if_false', cond, target: labelEnd });

    this.visitBlock(stmt.body);
    this.emit({ kind: 'goto', target: labelStart });
    this.emit({ kind: 'label', name: labelEnd });
    const afterBlock = this.newBlock(labelEnd);
    this.addEdge(loopBlock, afterBlock, 'false');
  }

  visitReturn(stmt) {
    if (stmt.value) {
      const t = this.visitExpr(stmt.value);
      this.emit({ kind: 'return', value: t });
    } else {
      this.emit({ kind: 'return', value: null });
    }
  }

  visitPrint(stmt) {
    for (const arg of (stmt.args || [])) {
      const t = this.visitExpr(arg);
      this.emit({ kind: 'call', dest: null, func: 'print', args: [t] });
    }
  }

  visitExprStmt(stmt) {
    this.visitExpr(stmt.expr);
  }

  visitAssignStmt(stmt) {
    const t = this.visitExpr(stmt.value);
    this.emit({ kind: 'copy', dest: stmt.name, src: t });
  }

  // ── Expressions (return temp or value) ────────────────
  visitExpr(expr) {
    if (!expr) return '?';
    switch (expr.nodeType) {
      case 'Literal': return String(expr.value);
      case 'Identifier': return expr.name;
      case 'BinOp': {
        const l = this.visitExpr(expr.left);
        const r = this.visitExpr(expr.right);
        const t = this.newTemp();
        this.emit({ kind: 'binop', dest: t, op: expr.op, left: l, right: r });
        return t;
      }
      case 'UnaryOp': {
        const v = this.visitExpr(expr.operand);
        const t = this.newTemp();
        this.emit({ kind: 'unop', dest: t, op: expr.op, operand: v });
        return t;
      }
      case 'Assign': {
        const t = this.visitExpr(expr.value);
        this.emit({ kind: 'copy', dest: expr.name, src: t });
        return expr.name;
      }
      case 'Call': {
        const args = (expr.args || []).map(a => this.visitExpr(a));
        for (const a of args) this.emit({ kind: 'param', value: a });
        const name = expr.callee ? expr.callee.name || '?' : '?';
        const t = this.newTemp();
        this.emit({ kind: 'call', dest: t, func: name, args });
        return t;
      }
      default: return '?';
    }
  }

  // ── AST-based IR (S-expression like) ─────────────────
  astIR(node, depth) {
    if (!node) return '';
    const indent = '  '.repeat(depth);
    const next = depth + 1;
    switch (node.nodeType) {
      case 'Program':
        return `(program\n${(node.body || []).map(s => astIR_stmt(s, next)).join('\n')}\n)`;
      default:
        return `(node ${node.nodeType})`;
    }
  }
}

// ── AST IR Printer (standalone) ────────────────────────────
function astIR_stmt(node, depth = 0) {
  if (!node) return '';
  const ind = '  '.repeat(depth);
  const n = depth + 1;
  switch (node.nodeType) {
    case 'VarDecl':
      return `${ind}(var-decl :type ${node.varType} :name ${node.name}${node.init ? `\n${ind}  :init ${astIR_expr(node.init, n)}` : ''})`;
    case 'Function':
      return `${ind}(func-decl :name ${node.name} :returns ${node.returnType}\n${ind}  :params (${(node.params||[]).map(p=>`${p.ptype} ${p.name}`).join(', ')})\n${ind}  :body\n${astIR_stmt(node.body, n)})`;
    case 'Block':
      return `${ind}(block\n${(node.body||[]).map(s=>astIR_stmt(s, n)).join('\n')}\n${ind})`;
    case 'If':
      return `${ind}(if\n${ind}  :cond ${astIR_expr(node.condition, n)}\n${ind}  :then\n${astIR_stmt(node.consequent, n)}${node.alternate ? `\n${ind}  :else\n${astIR_stmt(node.alternate, n)}` : ''}\n${ind})`;
    case 'While':
      return `${ind}(while\n${ind}  :cond ${astIR_expr(node.condition, n)}\n${ind}  :body\n${astIR_stmt(node.body, n)}\n${ind})`;
    case 'Return':
      return `${ind}(return${node.value ? ` ${astIR_expr(node.value, 0)}` : ''})`;
    case 'Print':
      return `${ind}(print ${(node.args||[]).map(a=>astIR_expr(a,0)).join(', ')})`;
    case 'ExprStmt':
      return `${ind}(expr-stmt ${astIR_expr(node.expr, n)})`;
    case 'Assign':
      return `${ind}(assign :target ${node.name} :value ${astIR_expr(node.value, 0)})`;
    default:
      return `${ind}(${node.nodeType || 'unknown'})`;
  }
}

function astIR_expr(node, depth = 0) {
  if (!node) return 'nil';
  switch (node.nodeType) {
    case 'Literal':    return String(node.value);
    case 'Identifier': return node.name;
    case 'BinOp':      return `(${node.op} ${astIR_expr(node.left)} ${astIR_expr(node.right)})`;
    case 'UnaryOp':    return `(${node.op} ${astIR_expr(node.operand)})`;
    case 'Assign':     return `(assign ${node.name} ${astIR_expr(node.value)})`;
    case 'Call':       return `(call ${node.callee ? node.callee.name : '?'} ${(node.args||[]).map(a=>astIR_expr(a)).join(' ')})`;
    default:           return `(expr)`;
  }
}
